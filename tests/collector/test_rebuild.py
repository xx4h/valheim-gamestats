"""The log → data.json rules of docs/ATTRIBUTION.md, one test per rule (test_<rule>)."""
import os
import unittest

from logs import Log, read_json  # first: puts collector/ (the package's directory) on the path

from valheim_gamestats.collector import Valheim

# docs/events.json: every event the plugin sends, and what it becomes
CONTRACT = read_json(os.path.join(os.path.dirname(__file__), "..", "..", "docs", "events.json"))["events"]

HOUR = 3600


def rebuild(log, now=None):
    return Valheim.rebuild(log.events(), log.at(now if now is not None else 10 * HOUR))


def gather(data, event, player=None):
    return sum(n for _, p, e, _, n in data["gather"] if e == event and (player is None or p == player))


class Presence(unittest.TestCase):
    def test_session_spawn_to_teardown(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).spawn(600, "Ragnar", 1001, 2).logout(HOUR, 1001)
        s, = rebuild(log)["sessions"]
        self.assertEqual((s["p"], s["s"], s["e"], s["end"], s["spawns"]), ("Ragnar", log.at(60), log.at(HOUR), "logout", 2))

    def test_session_open_while_online(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001)
        data = rebuild(log)
        self.assertEqual(data["online"], ["Ragnar"])
        self.assertIsNone(data["sessions"][0]["e"])

    def test_session_ends_on_restart(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).players(HOUR, 1).restart(HOUR + 100)
        s, = rebuild(log)["sessions"]
        self.assertEqual((s["e"], s["end"]), (log.at(HOUR), "restart"))  # the last sign of the old boot, not the new one

    def test_session_ends_when_nobody_is_connected(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).players(HOUR, 0)
        self.assertEqual(rebuild(log)["sessions"][0]["end"], "timeout")

    def test_session_relog_on_a_new_uid(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).spawn(HOUR, "Ragnar", 2002)
        a, b = rebuild(log)["sessions"]
        self.assertEqual((a["end"], a["e"], b["s"]), ("relog", log.at(HOUR), log.at(HOUR)))

    def test_platform_pairs_with_the_next_spawn(self):
        # old archives: the log named a connection's Steam account, the character spawned a few seconds later
        log = Log().restart(0).connect(50, "76561190000000001").connect(55, "76561190000000002")
        log.spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002).connect(2000, "76561190000000003").spawn(2700, "Bjorn", 1003)
        self.assertEqual(dict(rebuild(log)["_votes"]), {("76561190000000001", "Ragnar"): 1, ("76561190000000002", "Astrid"): 1})

    def test_death_is_the_destroyed_character(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002).death(500, "Astrid")
        data = rebuild(log)
        self.assertEqual(data["deaths"], [{"p": "Astrid", "t": log.at(500)}])
        self.assertEqual({s["p"]: s["deaths"] for s in data["sessions"]}, {"Ragnar": 0, "Astrid": 1})

    def test_raid_lists_everyone_online(self):
        # a raid hits the server: the player list is context, not credit for something someone did
        log = Log().restart(0).spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002).logout(100, 1002).raid(200)
        self.assertEqual(rebuild(log)["raids"], [{"t": log.at(200), "n": "army_eikthyr", "players": ["Ragnar"]}])


class Exploration(unittest.TestCase):
    def online(self):
        return Log().restart(0).plugin(1, "1.15.0").spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002)

    def test_zone_exact_credits_only_the_players_near(self):
        # the incident: Ragnar explores alone while Astrid is online at home — Astrid gets nothing
        log = self.online().location(500, "Crypt3", 12, -90).zone(500, 12, -90, ["Ragnar"]).zone(510, 13, -90, ["Ragnar"])
        zones = {f"{z['x']},{z['y']}": z for z in rebuild(log)["zones"]}
        self.assertEqual(zones["12,-90"]["by"], ["Ragnar"])
        self.assertEqual(zones["12,-90"]["l"], ["Crypt3"])
        self.assertEqual(zones["13,-90"]["by"], ["Ragnar"])  # zones without a location count too
        self.assertTrue(all(z["exact"] for z in zones.values()))

    def test_zone_exact_group_shares(self):
        log = self.online().zone(500, 1, 1, ["Astrid", "Ragnar"])
        self.assertEqual(rebuild(log)["zones"][0]["by"], ["Astrid", "Ragnar"])

    def test_zone_exact_nobody_near(self):
        # generated by the server itself (a new world's spawn area): nobody discovered it
        log = self.online().zone(500, 0, 0, [])
        self.assertEqual(rebuild(log)["zones"][0]["by"], [])

    def test_zone_exact_once_per_player(self):
        log = self.online().zone(500, 1, 1, ["Ragnar", "Ragnar"])
        self.assertEqual(rebuild(log)["zones"][0]["by"], ["Ragnar"])

    def test_zone_exact_zone_line_after_location(self):
        # locations are placed during generation, the zone line follows it: the exact list replaces the fallback
        log = self.online().location(500, "Dolmen02", 5, 5).zone(501, 5, 5, ["Astrid"])
        z, = rebuild(log)["zones"]
        self.assertEqual((z["by"], z["l"], z["exact"]), (["Astrid"], ["Dolmen02"], True))

    def test_zone_before_plugin_credits_everyone_online(self):
        # before plugin 1.15.0 the log is all there is — and the page says so (no "exact")
        log = Log().restart(0).spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002).location(500, "Crypt3", 12, -90)
        z, = rebuild(log)["zones"]
        self.assertEqual(z["by"], ["Astrid", "Ragnar"])
        self.assertNotIn("exact", z)

    def test_dungeon_entered(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001)
        log.g(100, e="enter", p="Ragnar", i="Crypt3", x=-1234, z=567, n=1)
        log.g(512, e="leave", p="Ragnar", i="Crypt3", x=-1234, z=567, n=1, s=412)
        log.g(900, e="leave", p="Astrid", i="Crypt4", x=10, z=20, n=1, s=60)  # its enter is before the archive
        self.assertEqual(rebuild(log)["visits"], [[log.at(100), "Ragnar", "Crypt3", -1234, 567, 412],
                                                  [log.at(840), "Astrid", "Crypt4", 10, 20, 60]])

    def test_dungeon_still_inside(self):
        log = Log().restart(0).spawn(60, "Ragnar", 1001).g(100, e="enter", p="Ragnar", i="Crypt3", x=1, z=2, n=1)
        self.assertIsNone(rebuild(log)["visits"][0][5])


class Combat(unittest.TestCase):
    def test_kill_every_attacker(self):
        # the plugin logs one kill line per attacker; each counts once for that player
        log = Log().restart(0).plugin(1, "1.15.0").spawn(60, "Ragnar", 1001).spawn(70, "Astrid", 1002)
        log.g(120, e="kill", p="Ragnar", i="Troll", n=1).g(120, e="kill", p="Astrid", i="Troll", n=1)
        log.g(180, e="kill", p="Ragnar", i="Greyling", n=3)
        data = rebuild(log)
        self.assertEqual((gather(data, "kill", "Ragnar"), gather(data, "kill", "Astrid")), (4, 1))

    def test_kill_per_weapon(self):
        log = Log().g(120, e="kw", p="Ragnar", i="MaceIron>Troll*1", n=1).g(180, e="kw", p="Ragnar", i="MaceIron>Troll*1", n=1)
        self.assertEqual([r for r in rebuild(log)["gather"] if r[2] == "kw"][0][3:], ["MaceIron>Troll*1", 2])

    def test_unaccounted_kills_have_no_player(self):
        # a death the plugin couldn't credit to anyone: summed per creature, never a player's kill
        log = Log().g(120, e="ukill", p="", i="Tick", n=1).g(180, e="ukill", p="", i="Tick", n=2)
        log.g(190, e="ukill", p="", i="Goblin/GoblinArcher*1", n=1)
        data = rebuild(log)
        got = sorted((r[1], r[3], r[4]) for r in data["gather"] if r[2] == "ukill")
        self.assertEqual(got, [("", "Goblin/GoblinArcher*1", 1), ("", "Tick", 3)])
        self.assertEqual(gather(data, "kill"), 0)

    def test_damage_taken_summed(self):
        log = Log().g(120, e="taken", p="Ragnar", i="", n=40).g(180, e="taken", p="Ragnar", i="", n=35)
        self.assertEqual(gather(rebuild(log), "taken", "Ragnar"), 75)

    def test_pet_killed_is_no_kill(self):
        log = Log().g(120, e="petdeath", p="Bess", i="Lox", n=1, k="Lox:1", x=0, z=0, hp=0, lv=0, by=["Ragnar"])
        log.g(150, e="pethp", p="Bess", i="Lox", n=1, k="Lox:1", dmg=50, hits=1, heal=0, min=0, hp=0, max=1000, by={"Ragnar": 50})
        data = rebuild(log)
        self.assertEqual(data["gather"], [])

    def test_plugin_line_broken_is_skipped(self):
        log = Log().raw(100, '[Gamestats] {"e":"kill","p":"Ragnar"').g(120, e="kill", p="Ragnar", i="Neck", n=1)
        log.g(130, e="kill", p="Ragnar", i="Neck", n="x")
        self.assertEqual(gather(rebuild(log), "kill"), 1)

    def test_plugin_warning_is_not_a_stat(self):
        log = Log().warn(100, "combat", "Method has zero rva")
        self.assertEqual(rebuild(log)["gather"], [])


class Gathering(unittest.TestCase):
    def test_picked_up_per_hour(self):
        log = Log().g(100, e="pick", p="Ragnar", i="Wood", n=37).g(160, e="pick", p="Ragnar", i="Wood", n=3)
        log.g(HOUR + 100, e="pick", p="Ragnar", i="Wood", n=5)
        rows = [r for r in rebuild(log)["gather"] if r[2] == "pick"]
        self.assertEqual([r[4] for r in rows], [40, 5])
        self.assertEqual(rows[0][0] % HOUR, 0)

    def test_gear_moved(self):
        log = Log()
        for i in range(25):
            log.g(100 + i, e="take", p="Ragnar", i="AxeBronze", q=2, c="Astrid", k="chest", x=37 + i, z=518, n=1)
        (item, crafter, q, moves), = rebuild(log)["custody"]
        self.assertEqual((item, crafter, q, len(moves)), ("AxeBronze", "Astrid", 2, 20))  # the last 20 moves of a copy
        self.assertEqual(moves[-1][1:], ["Ragnar", "take", "chest", 64, 512, 1])  # snapped to the 64 m zone


class EveryKind(unittest.TestCase):
    """Each event kind the contract lists as summed or as a gear move, one by one: a new kind can't slip through."""

    def test_every_summed_event(self):
        kinds = [e for e, c in CONTRACT.items() if c["becomes"] == "gather"]
        self.assertGreater(len(kinds), 15)
        log = Log()
        for i, e in enumerate(kinds):
            log.g(100 + i, e=e, p="Ragnar", i=f"thing-{e}", n=2).g(160 + i, e=e, p="Ragnar", i=f"thing-{e}", n=3)
        got = {(r[2], r[3]): r[4] for r in rebuild(log)["gather"]}
        for e in kinds:
            with self.subTest(event=e):
                self.assertEqual(got.get((e, f"thing-{e}")), 5)

    def test_every_custody_move(self):
        kinds = [e for e, c in CONTRACT.items() if c["becomes"] == "custody"]
        self.assertEqual(sorted(kinds), ["carry", "off", "on", "put", "take"])
        log = Log()
        for i, e in enumerate(kinds):
            log.g(100 + i, e=e, p="Ragnar", i="SwordIron", q=3, c="Astrid", k="chest", x=10 * i, z=0, n=1)
        (_, _, _, moves), = rebuild(log)["custody"]
        self.assertEqual([m[2] for m in moves], kinds)
        self.assertEqual(rebuild(log)["gather"], [])  # moves are not summed


class Body(unittest.TestCase):
    def test_peak_is_the_highest_not_a_sum(self):
        log = Log().g(100, e="peak", p="Ragnar", i="hp", n=115.1).g(160, e="peak", p="Ragnar", i="hp", n=120.5)
        log.g(220, e="peak", p="Ragnar", i="hp", n=90)
        (_, p, k, v), = rebuild(log)["peaks"]
        self.assertEqual((p, k, v), ("Ragnar", "hp", 120.5))

    def test_feats(self):
        log = Log().g(100, e="sprint", p="Ragnar", n=1, m=30.4, s=5).g(200, e="fall", p="Astrid", n=1, h=17.3)
        log.g(300, e="closecall", p="Ragnar", n=1, hp=3.2, max=120)
        self.assertEqual([f[1:] for f in rebuild(log)["feats"]],
                         [["Ragnar", "sprint", 30.4, 5], ["Astrid", "fall", 17.3, None], ["Ragnar", "closecall", 3.2, 120]])


